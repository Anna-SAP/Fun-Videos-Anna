def bar_of(t):
    import numpy as np
    i = int(np.searchsorted(T.BEATS, t + 0.025)) - 1
    return f'{i // 4 + 1}.{i % 4 + 1}'


def lines_in(sh):
    out = []
    for l in runes.LINES:
        if l.shot is sh:
            out.append(f"{l.id.replace('|', ' 行 ')}（{l.mode}）")
    return '；'.join(out)


